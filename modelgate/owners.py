"""Reviewers and code owners for promotion, from config/review.yaml.

`python -m modelgate codeowners` writes .gitlab/CODEOWNERS. With "Require approval from code
owners" on the protected default branch (Premium or Ultimate), a merge that changes the
champion, the gate rules or the flow's instructions then needs an owner's approval.
"""

from __future__ import annotations

import logging
import re
from typing import Any

from modelgate.common import Paths, load_yaml

logger = logging.getLogger(__name__)

OWNED_PATHS = (
    "/models/champion.json",
    "/config/thresholds.yaml",
    "/.gitlab/duo/",
    "/AGENTS.md",
)
_USERNAME = re.compile(r"^[A-Za-z0-9_][A-Za-z0-9_.-]*$")


def reviewers(paths: Paths) -> list[str]:
    """GitLab usernames from config/review.yaml, without @; empty when the file is absent.

    Raises ValueError for an entry that is not a valid GitLab username.
    """
    path = paths.config / "review.yaml"
    if not path.exists():
        return []
    names = [str(n).lstrip("@") for n in (load_yaml(path).get("reviewers") or [])]
    bad = [n for n in names if not _USERNAME.match(n)]
    if bad:
        raise ValueError(f"{path}: not GitLab usernames: {bad}")
    return names


def render_codeowners(names: list[str]) -> str:
    """The .gitlab/CODEOWNERS text for these reviewers."""
    lines = [
        "# Generated by `python -m modelgate codeowners` from config/review.yaml. Edit that file",
        "# and regenerate; do not edit this one by hand.",
        "#",
        '# Promotion is a person\'s decision. With "Require approval from code owners" on the',
        "# protected default branch (Premium or Ultimate), a merge that changes these files needs",
        "# an owner's approval.",
    ]
    if not names:
        lines += ["#", "# No reviewers in config/review.yaml yet, so no file has an owner."]
        return "\n".join(lines) + "\n"
    owners = " ".join(f"@{n}" for n in names)
    lines += ["", "[ModelGate promotion]", *(f"{path} {owners}" for path in OWNED_PATHS)]
    return "\n".join(lines) + "\n"


def main(paths: Paths) -> dict[str, Any]:
    """Write .gitlab/CODEOWNERS from config/review.yaml and return the reviewers used."""
    names = reviewers(paths)
    out = paths.root / ".gitlab" / "CODEOWNERS"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(render_codeowners(names), encoding="utf-8", newline="\n")
    logger.info("CODEOWNERS: %s", ", ".join(names) or "no reviewers configured")
    return {"reviewers": names, "file": ".gitlab/CODEOWNERS"}
